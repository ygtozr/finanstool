import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
const output = 'assets/overview-pilot';
await mkdir(output, { recursive: true });
await build({
  entryPoints: ['src/overview/main.jsx'], outfile: `${output}/app.js`, bundle: true,
  format: 'esm', target: ['safari15', 'chrome100'], minify: true,
  jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' },
});
// Keep the legacy entry and functions at their existing paths on Vercel.
await writeFile(`${output}/.generated`, 'Generated by pnpm build; do not edit bundles.\n');
